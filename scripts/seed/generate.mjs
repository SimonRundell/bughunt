/**
 * Regenerates api/sql/seed.sql from the puzzle/concept data in this
 * directory. Run with `node scripts/seed/generate.mjs` after editing any
 * track*.mjs or concepts.mjs file, then re-apply schema.sql + seed.sql to
 * your local database. Every puzzle is re-verified against the real
 * Pyodide harness before anything is written - this will fail loudly
 * (and not touch seed.sql) if fixed_code doesn't pass every test or
 * buggy_code doesn't fail at least one, matching BUILD.md 14's suggested
 * "verify every seeded puzzle" tool.
 */
import { writeFileSync } from 'node:fs'
import { deriveExpected, verify, runTest, verificationHash } from './build.mjs'
import { track1 } from './track1.mjs'
import { track2 } from './track2.mjs'
import { track3 } from './track3.mjs'
import { track4 } from './track4.mjs'
import { track5 } from './track5.mjs'
import { concepts } from './concepts.mjs'

// Puzzles whose buggy_code can genuinely loop forever - verified here by
// checking fixed_code only (this script has no timeout/interrupt wiring,
// that's a browser-only mechanism). See PROGRESS.md.
const SKIP_BUGGY_VERIFY = new Set(['the-search-that-hangs'])

const tracks = [
  {
    slug: 'spot-the-typo',
    title: 'Spot the Typo',
    summary: "Syntax errors: the code won't even run yet.",
    intro_md: "Every puzzle here fails before it even starts. You'll learn to read `SyntaxError` and `IndentationError` messages and fix the shape of the code, not its logic.",
    bug_focus: 'syntax',
    assist_level: 'none',
    sort_order: 1,
  },
  {
    slug: 'crash-course',
    title: 'Crash Course',
    summary: 'Runtime errors: the code runs, then crashes partway through.',
    intro_md: "These puzzles run until something goes wrong. You'll learn to read a traceback from the bottom up and recognise what each exception type is telling you.",
    bug_focus: 'runtime',
    assist_level: 'basic',
    sort_order: 2,
  },
  {
    slug: 'wrong-answer',
    title: 'Wrong Answer',
    summary: 'The code runs fine and gives you a confidently wrong answer.',
    intro_md: "No errors here - just the wrong result. You'll compare expected vs actual output and get used to checking boundary values by hand.",
    bug_focus: 'logic',
    assist_level: 'full',
    sort_order: 3,
  },
  {
    slug: 'deep-bugs',
    title: 'Deep Bugs',
    summary: 'Subtler logic bugs that need a trace table to really see.',
    intro_md: "These bugs hide in state, scope and recursion. You'll use trace tables and variable watch to see what's really happening, step by step.",
    bug_focus: 'logic',
    assist_level: 'full',
    sort_order: 4,
  },
  {
    slug: 'boss-fights',
    title: 'Boss Fights',
    summary: 'Bigger programs with more than one bug hiding in them.',
    intro_md: "Multiple bugs, longer code. You'll divide and conquer, build minimal examples, and work the full debugging loop end to end.",
    bug_focus: 'mixed',
    assist_level: 'full',
    sort_order: 5,
  },
]

const puzzles = [...track1, ...track2, ...track3, ...track4, ...track5]

let allVerified = true
for (const p of puzzles) {
  deriveExpected(p)
  if (SKIP_BUGGY_VERIFY.has(p.slug)) {
    const fixedResults = p.tests.map((t) => runTest(p.fixed_code, p.entry_mode, p.entry_name, t))
    const ok = fixedResults.every((r) => r.passed)
    console.log(ok ? `OK   ${p.slug} (fixed only - buggy hang case not exercised here)` : `FAIL ${p.slug}`)
    allVerified = ok && allVerified
  } else {
    allVerified = verify(p) && allVerified
  }
}
if (!allVerified) {
  console.error('\nOne or more puzzles failed verification - seed.sql NOT written. Fix the puzzle data above and retry.')
  process.exit(1)
}
console.log(`\nAll ${puzzles.length} puzzles verified.\n`)

/** MySQL string literal escaping (backslash and single-quote). */
function sqlStr(value) {
  if (value === null || value === undefined) return 'NULL'
  return "'" + String(value).replace(/\\/g, '\\\\').replace(/'/g, "''") + "'"
}

function sqlBool(value) {
  return value ? '1' : '0'
}

function sqlNum(value) {
  return value === null || value === undefined ? 'NULL' : String(value)
}

const lines = []
lines.push('-- Generated by `node scripts/seed/generate.mjs` - do not hand-edit.')
lines.push(`-- Seeds all ${tracks.length} tracks, ${concepts.length} concepts and ${puzzles.length} puzzles.`)
lines.push('-- Every puzzle was verified against the real harness before being included here')
lines.push('-- (fixed_code passes every test, buggy_code fails at least one) - see PROGRESS.md.')
lines.push('')

lines.push('-- Tracks')
for (const t of tracks) {
  lines.push(
    `INSERT INTO bh_tracks (slug, title, summary, intro_md, bug_focus, assist_level, sort_order, status) VALUES ` +
      `(${sqlStr(t.slug)}, ${sqlStr(t.title)}, ${sqlStr(t.summary)}, ${sqlStr(t.intro_md)}, ${sqlStr(t.bug_focus)}, ${sqlStr(t.assist_level)}, ${sqlNum(t.sort_order)}, 'published');`,
  )
}
lines.push('')

lines.push('-- Concepts')
for (const c of concepts) {
  lines.push(`INSERT INTO bh_concepts (slug, title, summary, lesson_md) VALUES (${sqlStr(c.slug)}, ${sqlStr(c.title)}, ${sqlStr(c.summary)}, ${sqlStr(c.lesson_md)});`)
}
lines.push('')

lines.push('-- Puzzles, tests, hints, bugs, concept links')
let puzzleSortOrder = {}
for (const p of puzzles) {
  puzzleSortOrder[p.track] = (puzzleSortOrder[p.track] ?? 0) + 1
  const sortOrder = puzzleSortOrder[p.track]
  const trackSub = `(SELECT id FROM bh_tracks WHERE slug = ${sqlStr(p.track)})`

  const hash = verificationHash(p)
  lines.push(
    `INSERT INTO bh_puzzles (slug, track_id, title, sort_order, difficulty, xp, bug_type, brief_md, buggy_code, fixed_code, entry_mode, entry_name, explanation_md, spot_it_md, predict_prompt_md, status, verified_hash, verified_at) VALUES (` +
      `${sqlStr(p.slug)}, ${trackSub}, ${sqlStr(p.title)}, ${sqlNum(sortOrder)}, ${sqlNum(p.difficulty)}, NULL, ${sqlStr(p.bug_type)}, ` +
      `${sqlStr(p.brief_md)}, ${sqlStr(p.buggy_code)}, ${sqlStr(p.fixed_code)}, ${sqlStr(p.entry_mode)}, ${sqlStr(p.entry_name ?? null)}, ` +
      `${sqlStr(p.explanation_md)}, ${sqlStr(p.spot_it_md ?? null)}, ${sqlStr(p.predict_prompt_md ?? null)}, 'published', ${sqlStr(hash)}, NOW());`,
  )
  const puzzleSub = `(SELECT id FROM bh_puzzles WHERE slug = ${sqlStr(p.slug)})`

  p.tests.forEach((t, i) => {
    lines.push(
      `INSERT INTO bh_puzzle_tests (puzzle_id, sort_order, label, args_py, kwargs_py, stdin_text, expect_kind, expect_py, compare_mode, is_hidden) VALUES (` +
        `${puzzleSub}, ${sqlNum(i + 1)}, ${sqlStr(t.label)}, ${sqlStr(t.args_py ?? null)}, ${sqlStr(t.kwargs_py ?? null)}, ${sqlStr(t.stdin_text ?? null)}, ` +
        `${sqlStr(t.expect_kind)}, ${sqlStr(t.expect_py)}, ${sqlStr(t.compare_mode ?? 'exact')}, ${sqlBool(t.hidden)});`,
    )
  })

  for (const h of p.hints) {
    lines.push(`INSERT INTO bh_hints (puzzle_id, tier, hint_md) VALUES (${puzzleSub}, ${sqlNum(h.tier)}, ${sqlStr(h.hint_md)});`)
  }

  p.bugs.forEach((b, i) => {
    const conceptSub = b.concept ? `(SELECT id FROM bh_concepts WHERE slug = ${sqlStr(b.concept)})` : 'NULL'
    lines.push(
      `INSERT INTO bh_puzzle_bugs (puzzle_id, sort_order, line_start, line_end, bug_type, concept_id, what_md, fix_md) VALUES (` +
        `${puzzleSub}, ${sqlNum(i + 1)}, ${sqlNum(b.line_start)}, ${sqlNum(b.line_end)}, ${sqlStr(b.bug_type)}, ${conceptSub}, ${sqlStr(b.what_md)}, ${sqlStr(b.fix_md)});`,
    )
  })

  for (const conceptSlug of p.concepts) {
    lines.push(
      `INSERT INTO bh_puzzle_concepts (puzzle_id, concept_id) VALUES (${puzzleSub}, (SELECT id FROM bh_concepts WHERE slug = ${sqlStr(conceptSlug)}));`,
    )
  }
  lines.push('')
}

writeFileSync('E:/bughunt/api/sql/seed.sql', lines.join('\n') + '\n', 'utf-8')
console.log(`Wrote api/sql/seed.sql: ${tracks.length} tracks, ${concepts.length} concepts, ${puzzles.length} puzzles.`)
